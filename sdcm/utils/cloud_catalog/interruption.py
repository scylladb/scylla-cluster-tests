"""Spot interruption buckets per region and instance type, kept in `data/instance_catalog/interruption.yaml`.

Sizing reads the file offline, so config resolution never makes a network call. `sct.py sizing
update-interruption` refreshes it. Buckets follow the AWS Spot Instance Advisor ranges: 0 = <5%, 1 = 5-10%,
2 = 10-15%, 3 = 15-20%, 4 = >20% of instances interrupted per month.

Only AWS publishes per-type data today. Azure's `SpotResources` eviction-rate table returns nothing to the
SCT service principal, and GCE and OCI have no per-type signal (SCT-707).
"""

import logging
from pathlib import Path

import requests
import yaml

LOG = logging.getLogger(__name__)

INTERRUPTION_FILE = "interruption.yaml"
SPOT_ADVISOR_URL = "https://spot-bid-advisor.s3.amazonaws.com/spot-advisor-data.json"
#: Regions SCT builders run in (vars/getJenkinsLabels.groovy).
AWS_REGIONS = (
    "us-east-1",
    "us-east-2",
    "us-west-2",
    "ca-central-1",
    "eu-west-1",
    "eu-west-2",
    "eu-west-3",
    "eu-north-1",
    "eu-central-1",
)


def fetch_aws_buckets(instance_types: set[str], regions: tuple[str, ...] = AWS_REGIONS) -> dict[str, dict[str, int]]:
    """Return {region: {instance_type: bucket}} for Linux, from the public Spot Instance Advisor data."""
    response = requests.get(SPOT_ADVISOR_URL, timeout=60)
    response.raise_for_status()
    advisor = response.json()["spot_advisor"]
    buckets = {}
    for region in regions:
        linux = advisor.get(region, {}).get("Linux", {})
        buckets[region] = {
            instance_type: linux[instance_type]["r"]
            for instance_type in sorted(instance_types)
            if instance_type in linux
        }
    return buckets


def write_interruption_file(path: Path, data: dict[str, dict[str, dict[str, int]]]) -> None:
    header = (
        "# Spot interruption bucket per cloud, region and instance type (0 = <5% ... 4 = >20%).\n"
        "# Generated by `sct.py sizing update-interruption`; do not edit by hand.\n"
    )
    path.write_text(header + yaml.safe_dump(data, sort_keys=True), encoding="utf-8")


def load_interruption_file(path: Path) -> dict[str, dict[str, dict[str, int]]]:
    if not path.exists():
        return {}
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}
