"""io_properties for minicloud db guests, which share one host drive between them."""

from fractions import Fraction
from pathlib import Path

import yaml

from sdcm.utils.minicloud.endpoint import is_minicloud_active
from sdcm.utils.minicloud.preflight import db_guest_count

# only these keys are scaled; the other keys of a disk entry are copied unchanged
IO_PROPERTY_KEYS = ("read_iops", "read_bandwidth", "write_iops", "write_bandwidth")


def scale_io_properties(text: str, guests: int, margin: float) -> str:
    """Split the host io_properties yaml evenly between ``guests`` db guests.

    ``margin`` is the fraction of each value kept back for the loader, the monitor and the host.
    The rest is divided by ``guests`` and rounded down.
    """
    share = (1 - Fraction(str(margin))) / guests
    disks = []
    for disk in yaml.safe_load(text)["disks"]:
        scaled = dict(disk)
        for key in IO_PROPERTY_KEYS:
            if key in scaled:
                scaled[key] = int(Fraction(scaled[key]) * share)
        disks.append(scaled)

    header = f"# per-guest share generated by SCT: host figure / {guests} db guests, margin {margin:.0%}\n"
    return header + yaml.safe_dump({"disks": disks}, sort_keys=False)


def override_content(config_file: Path, text: str, params) -> str:
    """Return the text to deploy for a scylla.d override file.

    On minicloud, io_properties.yaml is scaled to one db guest's share of the host drive.
    Every other file, and every run outside minicloud, is deployed as written.
    """
    if not is_minicloud_active(params) or config_file.name != "io_properties.yaml":
        return text
    return scale_io_properties(text, db_guest_count(params), params.get("minicloud_io_properties_margin"))
